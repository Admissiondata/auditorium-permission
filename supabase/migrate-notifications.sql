-- ==== 26. NOTIFICATIONS ====
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id text not null,
  title text not null,
  message text not null default '',
  module text not null default '',
  reference_id text not null default '',
  link text not null default '',
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notifications_user_idx on public.notifications (user_id, is_read);
create index if not exists notifications_created_idx on public.notifications (created_at);

alter table public.notifications enable row level security;
drop policy if exists "Allow all on notifications" on public.notifications;
create policy "Allow all on notifications" on public.notifications for all using (true) with check (true);

-- ==== 12. ROLE-MODULE PERMISSION MATRIX ====
-- module_permissions defines which roles may access each module and the action
-- (request / approve / manage / stock / view / none). Admin edits this freely.
create table if not exists public.module_permissions (
  id bigint generated by default as identity primary key,
  module text not null,
  role text not null,
  action text not null default 'view',
  created_at timestamptz not null default now(),
  unique (module, role)
);

alter table public.module_permissions enable row level security;
drop policy if exists "Allow all on module_permissions" on public.module_permissions;
create policy "Allow all on module_permissions" on public.module_permissions for all using (true) with check (true);

