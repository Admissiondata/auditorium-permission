-- ==== 20. STOCK TRANSACTIONS ====
-- Every stock movement is recorded here so current_stock can always be derived
-- from history instead of being relied on as the single source of truth.
create table if not exists public.stock_transactions (
  id bigint generated by default as identity primary key,
  item_id bigint references public.purchase_stock (id) on delete set null,
  department text not null default '',
  item_name text not null,
  category text not null default 'misc',
  transaction_type text not null check (transaction_type in ('PURCHASE', 'OPENING', 'ISSUE', 'RETURN', 'TRANSFER_IN', 'TRANSFER_OUT', 'ADJUSTMENT', 'DAMAGE')),
  quantity numeric(14,2) not null default 0,
  previous_stock numeric(14,2) not null default 0,
  new_stock numeric(14,2) not null default 0,
  reference_type text not null default '',
  reference_id text not null default '',
  issued_by text not null default '',
  remarks text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists stock_transactions_item_idx on public.stock_transactions (item_id);
create index if not exists stock_transactions_department_idx on public.stock_transactions (department, item_name);

alter table public.stock_transactions enable row level security;
drop policy if exists "Allow all on stock_transactions" on public.stock_transactions;
create policy "Allow all on stock_transactions" on public.stock_transactions for all using (true) with check (true);

